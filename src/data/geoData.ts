/**
 * Filter and sort items dynamically:
 * Exact match / starts-with comes to top,
 * followed by word boundary match,
 * followed by substring contains,
 * followed by alphabetical order.
 */
export function filterAndSortGeoItems<T extends { name: string; code?: string }>(
  items: T[],
  query: string
): T[] {
  const q = query.trim().toLowerCase();
  if (!q) {
    return items;
  }

  const startsWithList: T[] = [];
  const wordStartsList: T[] = [];
  const containsList: T[] = [];

  for (const item of items) {
    const nameLower = item.name.toLowerCase();
    const codeLower = item.code ? item.code.toLowerCase() : '';

    if (nameLower === q || codeLower === q) {
      startsWithList.unshift(item);
    } else if (nameLower.startsWith(q) || codeLower.startsWith(q)) {
      startsWithList.push(item);
    } else {
      // Check if any word starts with query
      const words = nameLower.split(/\s+|-|\/|\(/);
      if (words.some(w => w.startsWith(q))) {
        wordStartsList.push(item);
      } else if (nameLower.includes(q) || codeLower.includes(q)) {
        containsList.push(item);
      }
    }
  }

  return [...startsWithList, ...wordStartsList, ...containsList];
}
